#!/usr/bin/env node
/**
 * Render the skill dependency table and validate the direction rule.
 *
 * Walks every skills/<name>/SKILL.md, reads its `skills:` frontmatter
 * dependencies, and writes docs/skill-dependencies.md — a generated table,
 * never hand-kept, so it is current by construction. Re-run after any
 * frontmatter change.
 *
 * Validation, from the communication model (skills/PHILOSOPHY.md):
 * dependencies point down the layers only — media on audiences/voices,
 * audiences and voices on the foundation, never upward. Layers are read off
 * the naming scheme (communication-fundamentals, voice-*, audience-*,
 * medium-*); a skill outside the model is unranked and may be depended on
 * from any layer, but when it declares dependencies of its own they are
 * checked for existence. A missing dependency or an upward edge exits 1
 * with the violations listed; clean exits 0.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const skillsDir = join(REPO, "skills");

const layerOf = (name) => {
  if (name === "communication-fundamentals") return "foundation";
  if (name.startsWith("voice-")) return "voice";
  if (name.startsWith("audience-")) return "audience";
  if (name.startsWith("medium-")) return "medium";
  return null; // outside the model
};
const RANK = { foundation: 0, voice: 1, audience: 1, medium: 2 };

// Collect every skill's frontmatter.
const skills = new Map();
for (const entry of readdirSync(skillsDir)) {
  const p = join(skillsDir, entry, "SKILL.md");
  try {
    if (!statSync(join(skillsDir, entry)).isDirectory()) continue;
    const src = readFileSync(p, "utf8");
    const m = src.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
    const fm = m ? (parse(m[1]) ?? {}) : {};
    skills.set(entry, {
      deps: fm.skills ?? [],
      deprecated: Boolean(fm.metadata?.deprecated),
    });
  } catch {
    // no SKILL.md — not a skill directory
  }
}

// Validate: every dependency exists, and no edge points up the model.
const violations = [];
for (const [name, { deps }] of skills) {
  const layer = layerOf(name);
  for (const dep of deps) {
    if (!skills.has(dep)) {
      violations.push(`${name} -> ${dep}: dependency does not exist`);
      continue;
    }
    const depLayer = layerOf(dep);
    if (layer && depLayer && RANK[depLayer] > RANK[layer]) {
      violations.push(`${name} (${layer}) -> ${dep} (${depLayer}): dependency points up the model`);
    }
  }
}

// Render the table: the model's skills first by layer, then any other skill
// that declares dependencies.
const rows = [...skills.entries()]
  .filter(([name, { deps }]) => layerOf(name) || deps.length > 0)
  .sort(([a], [b]) => {
    const ra = RANK[layerOf(a)] ?? 99;
    const rb = RANK[layerOf(b)] ?? 99;
    return ra - rb || a.localeCompare(b);
  })
  .map(([name, { deps, deprecated }]) => {
    const layer = layerOf(name) ?? "—";
    const dep = deps.length ? deps.map((d) => `\`${d}\``).join(", ") : "—";
    const note = deprecated ? " (deprecated)" : "";
    return `| \`${name}\`${note} | ${layer} | ${dep} |`;
  });

const doc = `# Skill dependencies

Generated by \`scripts/skill-dependencies.mjs\` from each skill's \`skills:\`
frontmatter — do not edit by hand; re-run the script after any frontmatter
change. Dependencies point down the communication model's layers (foundation →
voice/audience → medium); the script fails on an upward edge or a missing
dependency. The drawn model is \`docs/diagrams/communication.d2\`.

| Skill | Layer | Depends on |
| --- | --- | --- |
${rows.join("\n")}
`;

writeFileSync(join(REPO, "docs", "skill-dependencies.md"), doc);

if (violations.length) {
  console.error("dependency violations:");
  for (const v of violations) console.error(`  ${v}`);
  process.exit(1);
}
console.log(`docs/skill-dependencies.md written: ${rows.length} skills, no violations.`);
